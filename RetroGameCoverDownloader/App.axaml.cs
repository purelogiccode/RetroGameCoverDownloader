using System.Diagnostics.CodeAnalysis;
using Avalonia;
using Avalonia.Controls;
using Avalonia.Controls.ApplicationLifetimes;
using Avalonia.Markup.Xaml;
using Avalonia.Threading;
using RetroGameCoverDownloader.Services;
using RetroGameCoverDownloader.ViewModels;
using Serilog;
using MessageBoxIcon = MsBox.Avalonia.Enums.Icon;

namespace RetroGameCoverDownloader;

[SuppressMessage("ReSharper", "PartialTypeWithSinglePart", Justification = "The other part is generated by the Avalonia XAML compiler.")]
public partial class App : Application
{
    private static int _shutdownGuard;

    public override void Initialize()
    {
        AvaloniaXamlLoader.Load(this);
    }

    public override void OnFrameworkInitializationCompleted()
    {
        LogConfig.Initialize();

        Dispatcher.UIThread.UnhandledException += OnUiThreadUnhandledException;
        AppDomain.CurrentDomain.UnhandledException += OnAppDomainUnhandledException;
        TaskScheduler.UnobservedTaskException += OnUnobservedTaskException;

        _ = ApplicationStatsService.TrackLaunchAsync();

        if (ApplicationLifetime is IClassicDesktopStyleApplicationLifetime desktop)
        {
            desktop.ShutdownMode = ShutdownMode.OnMainWindowClose;

            var viewModel = new MainViewModel();
            var mainWindow = new MainWindow(viewModel);
            desktop.MainWindow = mainWindow;

            ApplyCommandLineArguments(desktop.Args, viewModel);

            desktop.Exit += (_, _) => Log.CloseAndFlush();
        }

        base.OnFrameworkInitializationCompleted();
    }

    private static void ApplyCommandLineArguments(string[]? args, MainViewModel viewModel)
    {
        if (args is null || args.Length == 0) return;

        string? romPath = null;
        string? coverPath = null;

        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            if (arg.Equals("/rom", StringComparison.OrdinalIgnoreCase) ||
                arg.Equals("--rom", StringComparison.OrdinalIgnoreCase))
            {
                if (i + 1 < args.Length) romPath = args[++i];
            }
            else if (arg.Equals("/cover", StringComparison.OrdinalIgnoreCase) ||
                     arg.Equals("--cover", StringComparison.OrdinalIgnoreCase))
            {
                if (i + 1 < args.Length) coverPath = args[++i];
            }
        }

        if (romPath == null && coverPath == null && args.Length >= 2)
        {
            romPath = args[0];
            coverPath = args[1];
        }

        if (!string.IsNullOrWhiteSpace(romPath)) viewModel.RomFolderPath = romPath;
        if (!string.IsNullOrWhiteSpace(coverPath)) viewModel.CoverFolderPath = coverPath;
    }

    private static void OnUiThreadUnhandledException(object? sender, DispatcherUnhandledExceptionEventArgs e)
    {
        e.Handled = true;

        if (Interlocked.Exchange(ref _shutdownGuard, 1) != 0) return;

        try
        {
            Log.Fatal(e.Exception, "An unhandled UI thread exception occurred.");
            BugReportService.LogErrorSync(e.Exception, "An unhandled UI thread exception occurred.");
        }
        catch (Exception logEx)
        {
            WriteCriticalLog("unhandled UI thread", e.Exception, logEx);
        }

        Dispatcher.UIThread.Post(() => _ = ShowFatalErrorAndShutdownAsync());
    }

    private static async Task ShowFatalErrorAndShutdownAsync()
    {
        try
        {
            await AppDialogs.ShowMessageAsync(
                "An unexpected error occurred. The application will now close. A bug report has been saved to error.log and sent to the developer.",
                "Unhandled Exception",
                MessageBoxIcon.Error);
        }
        catch
        {
            // Ignore message box failure
        }

        if (Application.Current?.ApplicationLifetime is IClassicDesktopStyleApplicationLifetime desktop)
            desktop.Shutdown();
    }

    private static void OnAppDomainUnhandledException(object sender, UnhandledExceptionEventArgs e)
    {
        try
        {
            var exception = e.ExceptionObject as Exception ??
                            new InvalidOperationException($"Non-exception object thrown: {e.ExceptionObject}");
            Log.Fatal(exception, "An unhandled AppDomain exception occurred.");
            BugReportService.LogErrorSync(exception, "An unhandled AppDomain exception occurred.");
        }
        catch (Exception logEx)
        {
            WriteCriticalLog("unhandled AppDomain", e.ExceptionObject as Exception, logEx);
        }
    }

    private static void OnUnobservedTaskException(object? sender, UnobservedTaskExceptionEventArgs e)
    {
        try
        {
            Log.Fatal(e.Exception, "An unobserved task exception occurred.");
            BugReportService.LogErrorSync(e.Exception, "An unobserved task exception occurred.");
        }
        catch (Exception logEx)
        {
            WriteCriticalLog("unobserved task", e.Exception, logEx);
        }

        e.SetObserved();
    }

    private static void WriteCriticalLog(string context, Exception? original, Exception loggingFailure)
    {
        try
        {
            var message = $"[{DateTime.Now}] CRITICAL: BugReportService failed during {context}. " +
                          $"Original: {original?.Message ?? "unknown"}. Logging error: {loggingFailure.Message}";
            File.AppendAllText("critical_startup_error.log", message + Environment.NewLine);
        }
        catch
        {
            // Last resort - ignore
        }
    }
}
